function generateHistory(baseRate: number, days: number, volatility: number = 0.004): { date: string; rate: number }[] {
  const result: { date: string; rate: number }[] = [];
  const now = new Date();
  let current = baseRate;

  for (let i = days; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    // Deterministic pseudo-random variation based on day
    const seed = Math.sin(i * 12.9898 + baseRate * 78.233);
    const delta = (seed * volatility * current);
    current = +(current + delta * 0.3).toFixed(5);
    result.push({
      date: d.toISOString().split('T')[0],
      rate: +(current).toFixed(5)
    });
  }
  // ensure last day matches current
  result[result.length - 1].rate = baseRate;
  return result;
}

